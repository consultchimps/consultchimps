const chunk = (): Uint8Array =>
  Uint8Array.from(Buffer.from(CHUNK_BASE64, "base64"));

const sha256 = (bytes: Uint8Array): string =>
  createHash("sha256").update(bytes).digest("hex");

/** The committed artifact, read the way a browser caller would supply it. */
const wasmBytes = async (): Promise<Uint8Array> =>
  new Uint8Array(
    await readFile(new URL("../wasm/xpress9.wasm", import.meta.url)),
  );

async function rejection(
  promise: Promise<unknown>,
): Promise<ConsultChimpsError> {
  try {
    await promise;
  } catch (error) {
    expect(error).toBeInstanceOf(ConsultChimpsError);
    return error as ConsultChimpsError;
  }
  throw new Error("expected the call to be refused");
}

function refusal(call: () => unknown): ConsultChimpsError {
  try {
    call();
  } catch (error) {
    expect(error).toBeInstanceOf(ConsultChimpsError);
    return error as ConsultChimpsError;
  }
  throw new Error("expected the call to be refused");
}

/**
 * Nothing the toolchain, the decoder or the host says may reach a message or a
 * detail. These are the words that would give it away: the decoder's own status
 * strings, an Emscripten abort, a Node filesystem error, a URL.
 */
const upstreamMarkers = [
  "Xpress9",
  "Assert",
  "Decoder",
  "RuntimeError",
  "Aborted",
  "ENOENT",
  "http",
  "file:",
];

function assertNothingLeaked(error: ConsultChimpsError): void {
  const text = `${error.message} ${JSON.stringify(error.details)}`;
  for (const marker of upstreamMarkers) {
    expect(text.includes(marker)).toBe(false);
  }
  expect(error.cause).toBeUndefined();
}

describe("loadXpress9 configuration", () => {
  const cases: ReadonlyArray<readonly [string, Xpress9RuntimeConfig]> = [
    ["neither a locator nor bytes", {}],
    [
      "both a locator and bytes",
      { locateFile: () => "xpress9.wasm", wasmBinary: new Uint8Array([1]) },
    ],
    [
      "a locator that is not a function",
      { locateFile: "xpress9.wasm" as unknown as (name: string) => string },
    ],
    ["an empty byte array", { wasmBinary: new Uint8Array(0) }],
    [
      "bytes that are not a Uint8Array",
      { wasmBinary: [0, 1, 2] as unknown as Uint8Array },
    ],
  ];

  for (const [label, config] of cases) {
    it(`refuses ${label} before touching the host`, async () => {
      const error = await rejection(loadXpress9(config));
      expect(error.code).toBe("PBI_INVALID_OPTIONS");
      expect(error.details).toEqual({
        stage: "options",
        invalidOptions: [
          {
            path: "runtime.xpress9",
            requirement: "exactly one locator function or nonempty Uint8Array",
          },
        ],
      });
    });
  }
});

describe("loadXpress9 sources", () => {
  it("decodes a real chunk with no configuration at all", async () => {
    const decoder = await loadXpress9();
    try {
      const output = decoder.decompress(chunk(), CHUNK_UNCOMPRESSED_BYTES);
      expect(output.byteLength).toBe(CHUNK_UNCOMPRESSED_BYTES);
      expect(sha256(output)).toBe(CHUNK_EXPECTED_SHA256);
      // The decoded image is an Analysis Services backup, so it opens with the
      // byte order mark that its UTF-16 stream signature is written in.
      expect([output[0], output[1]]).toEqual([0xff, 0xfe]);
    } finally {
      decoder.close();
    }
  });

  it("decodes the same bytes from an injected binary", async () => {
    const decoder = await loadXpress9({ wasmBinary: await wasmBytes() });
    try {
      expect(
        sha256(decoder.decompress(chunk(), CHUNK_UNCOMPRESSED_BYTES)),
      ).toBe(CHUNK_EXPECTED_SHA256);
    } finally {
      decoder.close();
    }
  });

  it("asks a locator for the asset name and uses what it returns", async () => {
    const asked: string[] = [];
    const url = `data:application/wasm;base64,${Buffer.from(
      await wasmBytes(),
    ).toString("base64")}`;
    const decoder = await loadXpress9({
      locateFile: (fileName) => {
        asked.push(fileName);
        return url;
      },
    });
    try {
      expect(asked).toEqual(["xpress9.wasm"]);
      expect(
        sha256(decoder.decompress(chunk(), CHUNK_UNCOMPRESSED_BYTES)),
      ).toBe(CHUNK_EXPECTED_SHA256);
    } finally {
      decoder.close();
    }
  });

  it("returns a copy that outlives the decoder", async () => {
    const decoder = await loadXpress9();
    const output = decoder.decompress(chunk(), CHUNK_UNCOMPRESSED_BYTES);
    decoder.close();
    // Still readable, and still right, after the memory it was decoded into
    // has been freed.
    expect(sha256(output)).toBe(CHUNK_EXPECTED_SHA256);
    // A view onto the module's linear memory would report at least the 16 MiB
    // initial heap here, so this is the proof that it is a copy.
    expect(output.buffer.byteLength).toBe(CHUNK_UNCOMPRESSED_BYTES);
  });

  it("gives every decoder its own module and its own memory", async () => {
    const first = await loadXpress9();
    const second = await loadXpress9({ wasmBinary: await wasmBytes() });
    try {
      first.close();
      // Closing one decoder frees its context and its buffers. If the two
      // shared a module, this decode would read freed memory or fail.
      expect(sha256(second.decompress(chunk(), CHUNK_UNCOMPRESSED_BYTES))).toBe(
        CHUNK_EXPECTED_SHA256,
      );
    } finally {
      second.close();
    }
  });
});

describe("loadXpress9 failures", () => {
  it("reports a locator that throws as a load failure and says nothing else", async () => {
    const asked: string[] = [];
    const error = await rejection(
      loadXpress9({
        locateFile: (fileName) => {
          asked.push(fileName);
          throw new Error("http://internal.example/secret/module is gone");
        },
      }),
    );
    expect(asked).toEqual(["xpress9.wasm"]);
    expect(error.code).toBe("PBI_RUNTIME_UNAVAILABLE");
    expect(error.details).toEqual({ runtime: "xpress9", stage: "load" });
    assertNothingLeaked(error);
  });

  it("reports a locator whose result cannot be read as a load failure", async () => {
    const error = await rejection(
      loadXpress9({ locateFile: () => "data:application/wasm;base64,%%%%" }),
    );
    expect(error.code).toBe("PBI_RUNTIME_UNAVAILABLE");
    expect(error.details).toEqual({ runtime: "xpress9", stage: "load" });
    assertNothingLeaked(error);
  });

  it("reports a locator that returns nothing usable as a load failure", async () => {
    const error = await rejection(loadXpress9({ locateFile: () => "" }));
    expect(error.code).toBe("PBI_RUNTIME_UNAVAILABLE");
    expect(error.details).toEqual({ runtime: "xpress9", stage: "load" });
    assertNothingLeaked(error);
  });

  it("reports bytes that are not WebAssembly as a compile failure", async () => {
    const error = await rejection(
      loadXpress9({ wasmBinary: new TextEncoder().encode("not a module") }),
    );
    expect(error.code).toBe("PBI_RUNTIME_UNAVAILABLE");
    expect(error.details).toEqual({ runtime: "xpress9", stage: "compile" });
    assertNothingLeaked(error);
  });

  it("reports a truncated module as a compile failure", async () => {
    const error = await rejection(
      loadXpress9({ wasmBinary: (await wasmBytes()).slice(0, 2048) }),
    );
    expect(error.code).toBe("PBI_RUNTIME_UNAVAILABLE");
    expect(error.details).toEqual({ runtime: "xpress9", stage: "compile" });
    assertNothingLeaked(error);
  });
});

describe("Xpress9Decoder.decompress", () => {
  it("refuses a corrupted chunk without repeating the decoder's own words", async () => {
    const decoder = await loadXpress9();
    try {
      const damaged = chunk();
      // Well past the framing header, inside the Huffman-coded body.
      for (const index of [4096, 4097, 8192]) {
        damaged[index] = (damaged[index] ?? 0) ^ 0xff;
      }
      const error = refusal(() =>
        decoder.decompress(damaged, CHUNK_UNCOMPRESSED_BYTES),
      );
      expect(error.code).toBe("PBI_MODEL_UNREADABLE");
      expect(error.details).toEqual({ stage: "xpress9" });
      assertNothingLeaked(error);
    } finally {
      decoder.close();
    }
  });

  it("refuses a chunk whose declared size is wrong", async () => {
    const decoder = await loadXpress9();
    try {
      const error = refusal(() =>
        decoder.decompress(chunk(), CHUNK_UNCOMPRESSED_BYTES + 1),
      );
      expect(error.code).toBe("PBI_MODEL_UNREADABLE");
      expect(error.details).toEqual({ stage: "xpress9" });
    } finally {
      decoder.close();
    }
  });

  it("refuses a declared size that no framing could have produced", async () => {
    const decoder = await loadXpress9();
    try {
      for (const size of [0, -1, 1.5, Number.NaN]) {
        const error = refusal(() => decoder.decompress(chunk(), size));
        expect(error.code).toBe("PBI_MODEL_UNREADABLE");
        expect(error.details).toEqual({ stage: "xpress9" });
      }
      const empty = refusal(() =>
        decoder.decompress(new Uint8Array(0), CHUNK_UNCOMPRESSED_BYTES),
      );
      expect(empty.code).toBe("PBI_MODEL_UNREADABLE");
    } finally {
      decoder.close();
    }
  });
});

describe("Xpress9Decoder.close", () => {
  it("refuses every later decode and stays quiet about why", async () => {
    const decoder = await loadXpress9();
    decoder.close();
    const error = refusal(() =>
      decoder.decompress(chunk(), CHUNK_UNCOMPRESSED_BYTES),
    );
    expect(error.code).toBe("PBI_RUNTIME_UNAVAILABLE");
    expect(error.details).toEqual({ runtime: "xpress9", stage: "closed" });
    assertNothingLeaked(error);
  });

  it("is safe to call more than once", async () => {
    const decoder = await loadXpress9();
    decoder.close();
    expect(() => {
      decoder.close();
    }).not.toThrow();
  });
});
